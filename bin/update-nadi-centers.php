<?php
declare(strict_types=1);

// Refreshes the list of NADI centres from the public location page https://www.nadi.my/lokasi-nadi (the JSON
// that page loads). Keeps only the site code, name, district and state; staff names and phone numbers are not
// stored. Writes content/nadi-centers.csv (read by the portal's registration form: Negeri -> Daerah -> Pusat NADI)
// and docs/assets/js/nadi-centers.js (the same list for the docs/ preview, which has no server).
// Run from the project folder: php bin/update-nadi-centers.php

if (PHP_SAPI !== 'cli') {
    exit(1);
}
$root = dirname(__DIR__);
$clean = static function ($s): string {
    $s = preg_replace('/\s*[\/\x{2215}\x{2044}]\s*/u', ' / ', (string)$s);
    return trim((string)preg_replace('/\s+/u', ' ', (string)$s));
};
$context = stream_context_create(['http' => [
    'timeout' => 30,
    'header'  => "Accept: application/json\r\nReferer: https://www.nadi.my/lokasi-nadi\r\nUser-Agent: NADI-LMS centre list update\r\n",
]]);

$sites = [];
for ($page = 1, $last = 1; $page <= $last; $page++) {
    $json = @file_get_contents('https://www.nadi.my/api/proxy/admin/sites?page=' . $page . '&per_page=100', false, $context);
    $data = $json === false ? null : json_decode($json, true);
    if (!is_array($data) || !isset($data['data']) || !is_array($data['data'])) {
        fwrite(STDERR, "Could not read page $page. Nothing was changed.\n");
        exit(1);
    }
    $last = (int)($data['meta']['last_page'] ?? 1);
    foreach ($data['data'] as $s) {
        if ((int)($s['status'] ?? 0) !== 1 || !empty($s['deleted_at'])) {
            continue;
        }
        $state = (string)preg_replace('/^W\.?\s*P\.?\s+/i', 'W.P. ', $clean($s['state'] ?? ''));
        $district = $clean($s['district'] ?? '');
        if ($district === '') {
            // Perlis is one district; the source leaves some of its centres without one.
            $district = $state === 'Perlis' ? 'Perlis' : $clean($s['city'] ?? '');
        }
        $name = $clean($s['full_name'] ?? '') ?: 'NADI ' . $clean($s['name'] ?? '');
        $code = $clean($s['site_code'] ?? '');
        if ($code === '' || $state === '' || $district === '' || $name === 'NADI ') {
            continue;
        }
        $sites[$code] = [$code, $name, $district, $state];
    }
    usleep(300000);
}
if (count($sites) < 500) {
    fwrite(STDERR, 'Only ' . count($sites) . " centres found. Nothing was changed.\n");
    exit(1);
}
$sites = array_values($sites);

// Two centres with one name in the same district get their code added, so the list stays unambiguous.
$seen = [];
foreach ($sites as $s) {
    $seen[$s[3] . '|' . $s[2] . '|' . $s[1]] = ($seen[$s[3] . '|' . $s[2] . '|' . $s[1]] ?? 0) + 1;
}
foreach ($sites as &$s) {
    if ($seen[$s[3] . '|' . $s[2] . '|' . $s[1]] > 1) {
        $s[1] .= ' (' . $s[0] . ')';
    }
}
unset($s);
usort($sites, static function (array $a, array $b): int {
    return [strnatcasecmp($a[3], $b[3]), strnatcasecmp($a[2], $b[2]), strnatcasecmp($a[1], $b[1])] <=> [0, 0, 0];
});

$csv = fopen('php://temp', 'w+');
fputcsv($csv, ['Kod', 'Nama NADI', 'Daerah', 'Negeri'], ',', '"', '');
foreach ($sites as $s) {
    fputcsv($csv, $s, ',', '"', '');
}
rewind($csv);
file_put_contents($root . '/content/nadi-centers.csv', stream_get_contents($csv));
fclose($csv);

$js = '/* NADI centres [code, name, district, state]. Generated by bin/update-nadi-centers.php from'
    . ' https://www.nadi.my/lokasi-nadi on ' . date('Y-m-d') . ". Do not edit by hand. */\n"
    . 'window.NADI_CENTERS = ' . json_encode($sites, JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES) . ";\n";
file_put_contents($root . '/docs/assets/js/nadi-centers.js', $js);
$states = array_unique(array_column($sites, 3));
echo count($sites) . ' centres in ' . count($states) . " states written.\n";
